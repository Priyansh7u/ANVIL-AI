import { NextResponse, type NextRequest } from "next/server";
import { z } from "zod";
import { HAZARD_PROFILES, STAGE_LABEL, verificationLabel, type HazardStage, type IntelReport, type ResearchHazard } from "@/lib/core/hazard-intel";
import { jsonError, rateLimit } from "@/lib/http";
import { find, findById } from "@/lib/repo";

export const runtime = "nodejs";

const esc = (v: unknown) =>
  String(v ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c] as string);
const ist = (iso: unknown) => (typeof iso === "string" && iso ? `${new Date(iso).toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })} IST` : "Timestamp unavailable");
const safeHref = (u: unknown) => (typeof u === "string" && /^https:\/\//.test(u) ? esc(u) : "#");

/** Export a finished report as JSON or as a self-contained printable HTML page. */
export async function GET(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const limited = rateLimit(req, "research-export", 30, 60_000);
  if (limited) return limited;
  const { id } = await params;
  if (!z.string().uuid().safeParse(id).success) return jsonError(400, "INVALID_INPUT", "Invalid task id");
  const format = req.nextUrl.searchParams.get("format") === "html" ? "html" : "json";
  const task = await findById("ResearchTask", id);
  if (!task || task.kind !== "HAZARD_INTEL") return jsonError(404, "NOT_FOUND", "Task not found.");
  const [findings, sources] = await Promise.all([find("ResearchFinding", { taskId: id }, { limit: 200 }), find("ResearchSource", { taskId: id }, { limit: 200 })]);
  const place = (task.place as { label?: string }) ?? {};
  const report = task.report as IntelReport | undefined;
  const fname = `anvil-research-${String(place.label ?? "report").replace(/[^a-z0-9]+/gi, "-").toLowerCase()}-${id.slice(0, 8)}`;

  if (format === "json") {
    const { clientId: _c, ...t } = task;
    void _c;
    const payload = {
      exportedAt: new Date().toISOString(),
      notice: "Generated by ANVIL AI from public sources. Not an official government document. Follow official instructions and call 112 in an emergency.",
      task: { id, place: t.place, hazard: t.hazard, status: t.status, stage: t.stage, startedAt: t.startedAt, finishedAt: t.finishedAt, counts: t.counts, events: t.events },
      report,
      findings: findings.map(({ _id, taskId, ...f }) => (void _id, void taskId, f)),
      sources: sources.map(({ _id, taskId, ...s }) => (void _id, void taskId, s)),
    };
    return new NextResponse(JSON.stringify(payload, null, 2), {
      headers: { "Content-Type": "application/json; charset=utf-8", "Content-Disposition": `attachment; filename="${fname}.json"`, "Cache-Control": "no-store" },
    });
  }

  const byId = new Map(findings.map((f) => [String(f.fingerprint), f] as const));
  const ordered = (report?.latestFindingIds ?? []).map((fid) => byId.get(fid)).filter(Boolean) as typeof findings;
  const hz = HAZARD_PROFILES[(task.hazard as ResearchHazard) ?? "all"]?.label ?? String(task.hazard);
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>ANVIL research report — ${esc(place.label)}</title>
<style>body{font:14px/1.5 system-ui,sans-serif;color:#111;max-width:860px;margin:24px auto;padding:0 16px}h1{font-size:24px;margin:0}h2{font-size:16px;margin:24px 0 8px;border-bottom:1px solid #ccc;padding-bottom:4px}
.meta{color:#555;font-size:12px}.f{border:1px solid #ddd;border-radius:6px;padding:10px;margin:8px 0;break-inside:avoid}.b{display:inline-block;border:1px solid #999;border-radius:10px;padding:0 6px;font-size:11px;margin-right:4px}
.off{border-color:#0a7;color:#075}.warn{border-color:#c80;color:#850}q{font-style:italic;color:#333}a{color:#0645ad;word-break:break-all}.notice{background:#fff4e5;border:1px solid #e0a040;padding:8px;border-radius:6px}@media print{a{color:#000}}</style></head><body>
<p class="notice">Generated by ANVIL AI from public sources. <strong>Not an official government document.</strong> Follow official instructions. Emergency: 112.</p>
<h1>${esc(hz)} research — ${esc(place.label)}</h1>
<p class="meta">Status: ${esc(STAGE_LABEL[(task.stage as HazardStage) ?? "FAILED"] ?? task.stage)} · Started ${esc(ist(task.startedAt))} · Finished ${esc(ist(task.finishedAt))} · Task ${esc(id)}</p>
<h2>Executive summary</h2><p>${esc(report?.executiveSummary ?? "No report was produced.")}</p>
${report?.insufficientEvidence ? `<p class="notice">Insufficient evidence: ${esc(report.insufficiencyReason)}</p>` : ""}
<h2>Official advisories</h2>${report?.officialAdvisories.length ? `<ul>${report.officialAdvisories.map((a) => `<li>${esc(a.text)} — <a href="${safeHref(a.sourceUrl)}">${esc(a.sourceName)}</a> (${esc(ist(a.publishedAt))})</li>`).join("")}</ul>` : "<p>None found.</p>"}
<h2>Latest findings (${ordered.length})</h2>
${ordered
  .map(
    (f, i) => `<div class="f"><strong>[F${i + 1}] ${esc(f.title)}</strong><br>${esc(f.summary)}<br>
<span class="b ${f.sourceCategory === "OFFICIAL" ? "off" : ""}">${esc(verificationLabel({ sourceCategory: f.sourceCategory as "OFFICIAL", evidenceVerified: Boolean(f.evidenceVerified) }))}</span>
<span class="b ${f.freshness === "POTENTIALLY_STALE" || f.freshness === "TIMESTAMP_UNAVAILABLE" ? "warn" : ""}">${esc(String(f.freshness).replace(/_/g, " ").toLowerCase())}</span>
${(f.conflictsWith as string[] | undefined)?.length ? '<span class="b warn">conflicting information</span>' : ""}
<div class="meta">Source: <a href="${safeHref(f.sourceUrl)}">${esc(f.sourceName)}</a> · Published: ${esc(f.publishedAt ? `${ist(f.publishedAt)} (${String(f.publishedBasis ?? "").replace(/_/g, " ").toLowerCase()})` : "Timestamp unavailable")} · Retrieved: ${esc(ist(f.retrievedAt))} · Location relevance: ${esc(String(f.relevance).replace(/_/g, " ").toLowerCase())}</div>
${f.evidenceQuote ? `<div class="meta">Evidence: <q>${esc(f.evidenceQuote)}</q></div>` : ""}</div>`,
  )
  .join("")}
<h2>Affected areas</h2>${report?.affectedAreas.length ? `<ul>${report.affectedAreas.map((a) => `<li>${esc(a.name)} (${a.supportedBy.length} finding(s))</li>`).join("")}</ul>` : "<p>No area is supported by the evidence.</p>"}
<h2>Source reliability</h2><p>${esc(report?.reliability.text)}</p>
<h2>Freshness</h2><p>${report ? `${report.freshness.fresh} under 24 h · ${report.freshness.recent} 24–72 h · ${report.freshness.stale} potentially stale · ${report.freshness.unknown} without timestamp. Newest: ${esc(ist(report.freshness.newestPublishedAt))}.` : ""}</p>
<h2>Conflicts and gaps</h2><ul>${[...(report?.conflicts ?? []).map((c) => c.message), ...(report?.gaps ?? [])].map((x) => `<li>${esc(x)}</li>`).join("") || "<li>None detected.</li>"}</ul>
<h2>Recommended next steps</h2><ol>${(report?.nextSteps ?? []).map((n) => `<li>${esc(n.text)} <span class="b ${n.authority === "OFFICIAL" ? "off" : ""}">${n.authority === "OFFICIAL" ? "official" : "ANVIL general guidance"}</span></li>`).join("")}</ol>
<h2>Sources (${sources.length})</h2><ul>${sources.map((s) => `<li><a href="${safeHref(s.url)}">${esc(s.sourceName ?? s.host)}</a> — ${esc(String(s.category).toLowerCase())}, ${esc(String(s.status).toLowerCase())}</li>`).join("")}</ul>
<script>window.addEventListener("load",()=>setTimeout(()=>window.print(),300))</script></body></html>`;
  return new NextResponse(html, {
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      "Cache-Control": "no-store",
      "Content-Security-Policy": "default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; img-src 'none'",
    },
  });
}